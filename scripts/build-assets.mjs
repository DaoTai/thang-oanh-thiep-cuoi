async function icons() {
  const symbols = [];
  for (const [name, weight] of ICONS) {
    const file = weight === "regular" ? `${name}.svg` : `${name}-${weight}.svg`;
    const svg = await readFile(path.join(NM, "@phosphor-icons/core/assets", weight, file), "utf8");
    const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
    const id = weight === "regular" ? `i-${name}` : `i-${name}-${weight}`;
    symbols.push(`<symbol id="${id}" viewBox="${viewBox}">${inner}</symbol>`);
  }
  const sprite = `<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor">${symbols.join("")}</svg>\n`;
  await writeFile(path.join(PUB, "assets/icons.svg"), sprite);
  console.log(`icons  ${symbols.length} symbols`);
}

/* ------------------------------------------------------------------- fonts */

// [fontsource package, weights, styles]
const FONTS = [
  ["great-vibes", [400], ["normal"]],
  ["cormorant-garamond", [500], ["normal", "italic"]],
  ["cormorant-garamond", [600], ["normal"]],
  ["be-vietnam-pro", [400, 500, 600], ["normal"]],
];
const SUBSETS = ["vietnamese", "latin-ext", "latin"];

async function fonts() {
  const outDir = path.join(PUB, "assets/fonts");
  await rm(outDir, { recursive: true, force: true }); // drop faces no longer listed
  await mkdir(outDir, { recursive: true });
  let css = "/* Generated by scripts/build-assets.mjs from @fontsource packages. Do not edit by hand. */\n";

  for (const [pkg, weights, styles] of FONTS) {
    for (const weight of weights) {
      for (const style of styles) {
        const srcCss = path.join(NM, "@fontsource", pkg, style === "italic" ? `${weight}-italic.css` : `${weight}.css`);
        const text = await readFile(srcCss, "utf8");
        for (const block of text.match(/@font-face\s*{[^}]+}/g) ?? []) {
          const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
          const subset = woff2.slice(pkg.length + 1).replace(`-${weight}-${style}.woff2`, "");
          if (!SUBSETS.includes(subset)) continue;
          await copyFile(path.join(NM, "@fontsource", pkg, "files", woff2), path.join(outDir, woff2));
          const range = block.match(/unicode-range:\s*([^;]+);/)[1].trim();
          const family = block.match(/font-family:\s*'([^']+)'/)[1];
          css +=
            `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;` +
            `src:url(../assets/fonts/${woff2}) format('woff2');unicode-range:${range}}\n`;
        }
      }
    }
  }
  await writeFile(path.join(PUB, "css/fonts.css"), css);
  console.log("fonts  css/fonts.css written");
}

/* ---------------------------------------------------------------- calendar */

// Static .ics files: iOS Safari opens a served text/calendar file straight into
// the "Add to Calendar" sheet, which a JS-generated blob cannot do reliably.
const icsEscape = (s) => s.replace(/\\/g, "\\\\").replace(/;/g, "\\;").replace(/,/g, "\\,").replace(/\n/g, "\\n");
const icsTime = (iso) => new Date(iso).toISOString().replace(/[-:]/g, "").replace(/\.\d{3}/, "");

// RFC 5545: fold lines longer than 75 octets (UTF-8 aware).
function fold(line) {
  const out = [];
  let cur = "";
  for (const ch of line) {
    if (Buffer.byteLength(cur + ch) > (out.length ? 74 : 75)) {
      out.push(cur);
      cur = "";
    }
    cur += ch;
  }
  out.push(cur);
  return out.join("\r\n ");
}

async function calendar() {
  const { CONFIG } = await import(`file://${path.join(PUB, "js/config.js").replace(/\\/g, "/")}?t=${Date.now()}`);
  const couple = `${CONFIG.groom.short} & ${CONFIG.bride.short}`;
  const stamp = icsTime(new Date().toISOString());
  const vevent = (e) => [
    "BEGIN:VEVENT",
    `UID:${e.id}-2026@thang-oanh-wedding`,
    `DTSTAMP:${stamp}`,
    `DTSTART:${icsTime(e.start)}`,
    `DTEND:${icsTime(e.end)}`,
    `SUMMARY:${icsEscape(`${e.title} ${couple}`)}`,
    `LOCATION:${icsEscape(`${e.venue}, ${e.address}`)}`,
    `DESCRIPTION:${icsEscape(`Trân trọng kính mời bạn đến chung vui cùng ${couple}.`)}`,
    "BEGIN:VALARM", "ACTION:DISPLAY", `DESCRIPTION:${icsEscape(`Ngày mai: ${e.title}`)}`, "TRIGGER:-P1D", "END:VALARM",
    "BEGIN:VALARM", "ACTION:DISPLAY", `DESCRIPTION:${icsEscape(`${e.title} sau 2 giờ nữa`)}`, "TRIGGER:-PT2H", "END:VALARM",
    "END:VEVENT",
  ];
  const wrap = (events) =>
    ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Thang Oanh//Wedding Invitation//VI", "CALSCALE:GREGORIAN", "METHOD:PUBLISH",
      `X-WR-CALNAME:${icsEscape(`Đám cưới ${couple}`)}`, ...events.flatMap(vevent), "END:VCALENDAR"]
      .map(fold).join("\r\n") + "\r\n";

  const dir = path.join(PUB, "assets/calendar");
  await mkdir(dir, { recursive: true });
  for (const e of CONFIG.events) await writeFile(path.join(dir, `${e.id}.ics`), wrap([e]));
  await writeFile(path.join(dir, "tat-ca.ics"), wrap(CONFIG.events));
  console.log(`ics    ${CONFIG.events.length + 1} files`);
}

/* ------------------------------------------------------- share + favicon */

async function share() {
  // 1200x630 link-preview image (Zalo / Messenger / Facebook). JPEG for widest support.
  const buf = await upright(path.join(ALBUM, "NMT_0075.jpg"));
  await sharp(buf).resize(1200, 630, { fit: "cover", position: "attention" }).jpeg({ quality: 78, mozjpeg: true })
    .toFile(path.join(PUB, "assets/og-cover.jpg"));
  console.log("share  assets/og-cover.jpg");
}

// Source: assets-src/logo.png (the engraved rings, transparent PNG). Outside public/, so never deployed.
async function favicon() {
  const src = path.join(ROOT, "assets-src/logo.png");
  if (!existsSync(src)) return console.log("favicon skipped: assets-src/logo.png not found");
  const trimmed = await sharp(src).trim().toBuffer();
  const square = { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } };
  await sharp(trimmed).resize(48, 48, square).png().toFile(path.join(PUB, "favicon.png"));
  await sharp(trimmed).resize(160, 160, square).extend({ top: 10, bottom: 10, left: 10, right: 10, background: "#fbf6f5" })
    .flatten({ background: "#fbf6f5" }).png().toFile(path.join(PUB, "apple-touch-icon.png"));
  // Header logo: shown at 44px, so 132px covers 3x screens.
  await sharp(trimmed).resize(132, 132, square).webp({ quality: 86, alphaQuality: 90, effort: 6 })
    .toFile(path.join(PUB, "assets/logo.webp"));
  console.log("icon   favicon.png + apple-touch-icon.png + assets/logo.webp");
}

/* -------------------------------------------------------------------- main */

const steps = { photos, icons, fonts, calendar, share, favicon };
const only = process.argv[2];
await mkdir(path.join(PUB, "js"), { recursive: true });
await mkdir(path.join(PUB, "css"), { recursive: true });
for (const [name, fn] of Object.entries(steps)) {
  if (!only || only === name) await fn();
}
