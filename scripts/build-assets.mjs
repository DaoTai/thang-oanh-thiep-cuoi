// Dev-only asset pipeline. Nothing here ships to the browser except its output.
//
//   node scripts/build-assets.mjs            -> photos + icons + fonts
//   node scripts/build-assets.mjs photos     -> only one step (photos | icons | fonts)
//
// Outputs (all inside public/, the web root):
//   assets/album/web/<slug>-{480,960,1600}.webp   responsive photos (EXIF-rotated)
//   js/photos.js                                   photo list: size + tiny blur placeholder
//   assets/icons.svg                               Phosphor icon sprite (<use href="assets/icons.svg#i-heart">)
//   assets/fonts/*.woff2 + css/fonts.css           self-hosted fonts (latin, latin-ext, vietnamese)

import { readdir, readFile, writeFile, mkdir, copyFile, stat, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUB = path.join(ROOT, "public");
const NM = path.join(ROOT, "node_modules");

/* ------------------------------------------------------------------ photos */

const ALBUM = path.join(PUB, "assets/album");
const WEB = path.join(ALBUM, "web");
const WIDTHS = [480, 960, 1600];

// Same convention as album/thumbs: lowercase, spaces -> hyphens.
const slugOf = (file) => path.parse(file).name.toLowerCase().replace(/\s+/g, "-");

// Extra crops cut from album photos (fractions of the EXIF-rotated image).
// h is derived from the 3:4 portrait ratio, so only x, y and w are given.
const CROPS = [
  { id: "nmt_1013-groom", src: "NMT_1013.jpg", x: 0.05, y: 0.12, w: 0.44 },
  { id: "nmt_9720-bride", src: "NMT_9720.jpg", x: 0.02, y: 0.13, w: 0.5 },
];

async function emit(slug, input, srcMtime, list) {
  const img = sharp(input);
  const { width, height } = await img.metadata();
  for (const w of WIDTHS) {
    const out = path.join(WEB, `${slug}-${w}.webp`);
    if (existsSync(out) && (await stat(out)).mtimeMs > srcMtime) continue;
    await img.clone().resize({ width: w, withoutEnlargement: true }).webp({ quality: 74, effort: 5 }).toFile(out);
  }
  const lqip = await img.clone().resize({ width: 16 }).blur(1).webp({ quality: 40 }).toBuffer();
  list.push({ id: slug, w: width, h: height, lqip: `data:image/webp;base64,${lqip.toString("base64")}` });
  console.log(`photo  ${slug}  ${width}x${height}`);
}

// EXIF-rotated, full-resolution decode kept as a high-quality JPEG buffer.
const upright = (src) => sharp(src, { failOn: "none" }).rotate().jpeg({ quality: 95 }).toBuffer();

async function photos() {
  await mkdir(WEB, { recursive: true });
  const files = (await readdir(ALBUM)).filter((f) => /\.jpe?g$/i.test(f)).sort();
  const list = [];

  for (const file of files) {
    const src = path.join(ALBUM, file);
    const buf = await upright(src);
    const mtime = (await stat(src)).mtimeMs;
    await emit(slugOf(file), buf, mtime, list);

    for (const c of CROPS.filter((c) => c.src === file)) {
      const { width, height } = await sharp(buf).metadata();
      const w = Math.round(width * c.w);
      const h = Math.min(Math.round((w * 4) / 3), height - Math.round(height * c.y));
      const cropped = await sharp(buf)
        .extract({ left: Math.round(width * c.x), top: Math.round(height * c.y), width: w, height: h })
        .jpeg({ quality: 95 })
        .toBuffer();
      await emit(c.id, cropped, mtime, list);
    }
  }

  const js =
    "// Generated by scripts/build-assets.mjs. Do not edit by hand.\n" +
    `export const PHOTO_WIDTHS = ${JSON.stringify(WIDTHS)};\n` +
    `export const PHOTOS = ${JSON.stringify(list, null, 1)};\n`;
  await writeFile(path.join(PUB, "js/photos.js"), js);
}

